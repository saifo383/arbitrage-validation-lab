create table if not exists public.quant_paper_journal (
  id bigint generated by default as identity primary key,
  observed_at timestamptz not null default now(),
  candle_end timestamptz not null,
  source text not null default 'NDAX',
  strategy text not null,
  asset text not null,
  previous_signal text,
  signal text not null check (signal in ('LONG','CASH')),
  action text not null check (action in ('ENTER','EXIT','WAIT','HOLD')),
  close_price numeric,
  bid numeric,
  ask numeric,
  spread_pct numeric,
  ema50 numeric,
  ema150 numeric,
  target_weight numeric not null default 0,
  real_orders boolean not null default false,
  evidence jsonb not null default '{}'::jsonb,
  unique(strategy, asset, candle_end, signal)
);

alter table public.quant_paper_journal enable row level security;

create index if not exists quant_paper_journal_observed_idx
  on public.quant_paper_journal(observed_at desc);

create index if not exists quant_paper_journal_asset_idx
  on public.quant_paper_journal(strategy, asset, candle_end desc);

comment on table public.quant_paper_journal is
  'Paper-only audited strategy decision journal. Never records real order execution.';

